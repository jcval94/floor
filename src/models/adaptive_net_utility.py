"""Leakage-safe nonlinear directional model for the Adaptive Net Utility strategy.

The model predicts 10-session forward return from the same point-in-time feature
contract already available to Strategy League. Training uses scikit-learn, but
serving uses the pure-Python HistGradientBoosting interpreter shared with
``robust_range_v3``.

Model selection is deliberately aligned with trading economics: hyperparameters
are chosen on purged temporal folds using cost-adjusted long/short tail returns,
not in-sample regression fit. Validation selects only the operating threshold;
the blind test is opened once after every choice is frozen.
"""

from __future__ import annotations

import argparse
import json
import math
from collections import defaultdict
from dataclasses import dataclass
from pathlib import Path
from statistics import fmean, median
from typing import Any

from models.robust_range_v3 import export_hist_gradient_boosting, predict_head
from models.temporal_cv import purged_expanding_folds
from models.train_weekly_opportunity import (
    predict_weekly_opportunity,
    train_weekly_opportunity_model,
)


MODEL_NAME = "adaptive_net_utility_hgb"
MODEL_VERSION = "v1"
TARGET_END_FIELD = "target_end_date_q1"
TARGET_FIELD = "forward_return_q1"
TARGET_CLIP = 0.20
DEFAULT_ROUND_TRIP_COST = 0.0058

# Keep the model's production feature contract intentionally small. Every field
# below is already generated by league.market_features._feature_row, so a model
# that wins offline can be replayed and served without silently changing inputs.
FEATURE_NAMES: tuple[str, ...] = (
    "momentum_20",
    "rel_strength_20",
    "trend_context_m3",
    "drawdown_13w",
    "atr_ratio_14",
    "price_position_in_range_20",
)

